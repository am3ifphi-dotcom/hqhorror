#!/usr/bin/env python3
"""Subset the self-hosted Japanese webfont down to the glyphs this game actually uses.

Source : node_modules/@fontsource/shippori-mincho/files/shippori-mincho-japanese-400-normal.woff2
         (Shippori Mincho, SIL Open Font License 1.1 -- see public/assets/fonts/OFL.txt)
Output : public/assets/fonts/shippori-mincho-subset.woff2
         public/assets/fonts/fonts.css

Requires: fonttools + brotli  (pip install fonttools brotli)
Run from the repository root:  python3 tools/build_font.py
"""
import pathlib
import subprocess
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
SRC = (ROOT / "node_modules/@fontsource/shippori-mincho/files/"
       "shippori-mincho-japanese-400-normal.woff2")
OUT_DIR = ROOT / "public/assets/fonts"
OUT = OUT_DIR / "shippori-mincho-subset.woff2"

# 1. every character that appears in the shipped source ------------------------
text = set()
for pat in ("index.html", "src/style.css", "src/main.js",
            "src/engine/*.js", "src/game/*.js", "src/ui/*.js"):
    for f in ROOT.glob(pat):
        text |= set(f.read_text(encoding="utf-8"))

# 2. plus safety ranges so dynamic strings / user typing never tofu ------------
def add_range(a, b):
    text.update(chr(c) for c in range(a, b + 1))

add_range(0x20, 0x7E)          # ASCII
add_range(0xA0, 0xFF)          # latin-1
add_range(0x2000, 0x206F)      # general punctuation
add_range(0x3000, 0x303F)      # CJK symbols & punctuation  、。「」etc.
add_range(0x3040, 0x309F)      # hiragana
add_range(0x30A0, 0x30FF)      # katakana
add_range(0x3400, 0x4DBF)      # CJK ext A (rare, cheap insurance)
add_range(0xFF01, 0xFF60)      # full-width forms
add_range(0x2010, 0x203B)      # dashes / quotes
for ch in "…‥※♪♭●○◯×☆★※→←↑↓■□◆◇":
    text.add(ch)

chars = "".join(sorted(c for c in text if ord(c) > 0x1F and c != "\n"))
chars_file = ROOT / "tools/.font-chars.txt"
chars_file.write_text(chars, encoding="utf-8")

if not SRC.exists():
    sys.exit("missing " + str(SRC) + "  -> npm i @fontsource/shippori-mincho")

OUT_DIR.mkdir(parents=True, exist_ok=True)
cmd = [sys.executable, "-m", "fontTools.subset", str(SRC),
       "--text-file=" + str(chars_file),
       "--flavor=woff2",
       "--layout-features=*",
       "--name-IDs=0,1,2,3,4,5,6,13,14",
       "--no-hinting",
       "--drop-tables+=DSIG",
       "--output-file=" + str(OUT)]
print("$", " ".join(cmd))
subprocess.run(cmd, check=True)

# license copy -----------------------------------------------------------------
lic = ROOT / "node_modules/@fontsource/shippori-mincho/LICENSE"
if lic.exists():
    (OUT_DIR / "OFL.txt").write_text(lic.read_text(encoding="utf-8"), encoding="utf-8")

(OUT_DIR / "fonts.css").write_text("""/* Generated by tools/build_font.py -- do not edit by hand.
 * Shippori Mincho (subset: only the glyphs this game can display)
 * Source  : https://github.com/fontsource/shippori-mincho
 * Author  : The Shippori Mincho Project Authors (fontdasu/ShipporiMincho)
 * License : SIL Open Font License 1.1 (see OFL.txt in this directory)
 * Note    : the glyph set is SUBSET; it is not redistributed in full.
 */
@font-face {
  font-family: 'Shippori Mincho';
  font-style: normal;
  font-weight: 400;
  font-display: swap;
  src: url('/assets/fonts/shippori-mincho-subset.woff2') format('woff2');
}
""", encoding="utf-8")

print("wrote", OUT, round(OUT.stat().st_size / 1024, 1), "KB  (", len(chars), "chars )")
chars_file.unlink()
